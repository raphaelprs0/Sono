import Foundation

/// Langue de l’interface : le texte source est en français, l’anglais vient du dictionnaire ci-dessous.
/// Par défaut, celle du téléphone (français si le téléphone est en français, sinon anglais).
enum Lang {
    static let key = "sono-lang"
    static var current: String = {
        if let saved = UserDefaults.standard.string(forKey: key), saved == "fr" || saved == "en" { return saved }
        return Locale.preferredLanguages.first?.hasPrefix("fr") == true ? "fr" : "en"
    }()
    static var locale: Locale { Locale(identifier: current == "en" ? "en_US" : "fr_FR") }
}

/// Texte de l’interface dans la langue choisie ; {0}, {1}… sont remplacés par les valeurs données.
func L(_ text: String, _ values: Any...) -> String {
    var result = Lang.current == "en" ? (english[text] ?? text) : text
    for (index, value) in values.enumerated() { result = result.replacingOccurrences(of: "{\(index)}", with: "\(value)") }
    return result
}

/// Message venu du service en ligne (erreur, fil d’activité) : texte exact, ou gabarit avec des parties variables.
func LServer(_ message: String) -> String {
    guard Lang.current == "en" else { return message }
    if let exact = english[message] { return exact }
    for (pattern, key) in serverPatterns {
        guard let match = pattern.firstMatch(in: message, range: NSRange(message.startIndex..., in: message)) else { continue }
        let values = (1..<match.numberOfRanges).compactMap { Range(match.range(at: $0), in: message).map { String(message[$0]) } }
        return values.enumerated().reduce(english[key] ?? message) { $0.replacingOccurrences(of: "{\($1.offset)}", with: $1.element) }
    }
    return message
}

private let serverPatterns: [(NSRegularExpression, String)] = english.keys.filter { $0.contains("{0}") }.compactMap { key in
    let pattern = NSRegularExpression.escapedPattern(for: key).replacingOccurrences(of: #"\\?\{\d\\?\}"#, with: "(.+?)", options: .regularExpression)
    return (try? NSRegularExpression(pattern: "^" + pattern + "$")).map { ($0, key) }
}

